#pragma once

#include <memory>
#include <string>

#include <read_strategy.hpp>

namespace reader {

// Фабрика стратегий: единственное место в программе, которое знает
// соответствие «расширение файла → конкретный класс стратегии».
//
// Возвращает unique_ptr: вызывающий код становится единственным владельцем
// объекта стратегии, и память освобождается автоматически — при выходе
// из области видимости или при присваивании нового указателя.
//
// Если расширение неизвестно, возвращает nullptr (а не бросает исключение):
// неподдерживаемый файл — это нормальная ситуация при разборе аргументов CLI,
// её удобно обработать на месте и перейти к следующему файлу.
std::unique_ptr<IReadStrategy> makeReadStrategy(const std::string& path);

}  // namespace reader
