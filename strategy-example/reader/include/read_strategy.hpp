#pragma once

#include <string>

// ======================================================================================
//  Паттерн Strategy (стратегия)
// ======================================================================================
//
//  Задача: программа умеет читать файлы разных форматов (.json, .xlsx, в будущем —
//  SQL-дамп или .docx). Алгоритм чтения у каждого формата свой, но вызывающий код
//  во всех случаях делает одно и то же: «прочитай файл и выведи его в консоль».
//
//  Плохое решение — одна функция с цепочкой if/else по расширению:
//
//      if (ext == ".json")      { ...100 строк... }
//      else if (ext == ".xlsx") { ...100 строк... }
//      else if (ext == ".sql")  { ...100 строк... }
//
//  Такая функция растёт при каждом новом формате, смешивает в себе всю логику
//  и заставляет перекомпилировать себя при правке любого формата.
//
//  Решение Strategy: выносим каждый алгоритм в отдельный класс-наследник общего
//  интерфейса. Вызывающий код держит указатель на интерфейс и ничего не знает
//  о конкретных реализациях. Добавление формата = новый класс + одна строка
//  в фабрике; существующий код не меняется (принцип open/closed).
//
//  Механика C++: виртуальные функции. У класса с virtual-методами компилятор
//  создаёт таблицу виртуальных функций (vtable) — массив адресов реализаций,
//  а в каждом объекте хранит скрытый указатель на эту таблицу. Вызов
//  strategy->read(path) через указатель на базовый класс разрешается
//  не на этапе компиляции, а в рантайме: берём vptr объекта, в таблице находим
//  нужный слот, прыгаем по адресу. Это и называется динамическим полиморфизмом.
// ======================================================================================

namespace reader {

// Абстрактный базовый класс — общий интерфейс всех стратегий чтения.
class IReadStrategy {
public:
    // Виртуальный деструктор обязателен для любого класса, который удаляют
    // через указатель на базовый тип (у нас — через unique_ptr<IReadStrategy>).
    // Без virtual был бы вызван только ~IReadStrategy(), а деструктор наследника
    // не вызвался бы вообще — это undefined behavior и утечка ресурсов.
    virtual ~IReadStrategy() = default;

    // = 0 делает функцию чисто виртуальной (pure virtual): реализации в базовом
    // классе нет, наследник обязан её определить. Класс с такой функцией
    // абстрактный — создать объект IReadStrategy напрямую нельзя.
    //
    // Читает файл path и печатает его содержимое в std::cout.
    // Бросает std::runtime_error, если файл не открывается или имеет неверный формат.
    virtual void read(const std::string& path) const = 0;

    // Человекочитаемое имя стратегии — только для вывода в консоль.
    virtual std::string name() const = 0;
};

}  // namespace reader
